export const PROMPTS_BY_KEY = Object.fromEntries(
  PROMPTS.map((prompt) => [prompt.key, prompt]),
) as Record<PromptKey, PromptDefinition>;

export function isPromptKey(value: string): value is PromptKey {
  return (PROMPT_KEYS as readonly string[]).includes(value);
}
